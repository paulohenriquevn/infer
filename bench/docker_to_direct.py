#!/usr/bin/env python3
"""Converts a 'docker run ... "$IMAGE" <command>' script into a script that runs the command directly.

Usage: python3 docker_to_direct.py server-vllm.sh > server-vllm-direct.sh
Meant for instances whose environment already is the image's container (Vast.ai): keeps the -e
variables and the command, drops the docker options. The generated script expects PIDFILE and LOGFILE,
like server-sglang.sh with LAUNCH_MODE=direct, and keeps $PORT and $GPUS as variables.
"""
from __future__ import annotations

import re
import shlex
import sys


class InvalidScript(Exception):
    """The script does not have the shape 'docker run ... "$IMAGE" command'."""


def extract(text: str) -> tuple[dict[str, str], list[str]]:
    body = re.sub(r"`[^`]*`", " ", text)             # comments embedded in backticks
    body = re.sub(r"\\\n", " ", body)                # line continuations
    line = next((l for l in body.splitlines() if re.search(r"\bdocker run\b", l)), None)
    if line is None:
        raise InvalidScript("no 'docker run' line found")
    tokens = shlex.split(line[line.index("docker run"):], posix=True)
    if "$IMAGE" not in tokens:
        raise InvalidScript("'docker run' has no \"$IMAGE\" argument to split options from the command")
    i = tokens.index("$IMAGE")
    envs: dict[str, str] = {}
    opts = tokens[2:i]
    for j, tok in enumerate(opts):
        if tok == "-e":
            key, _, value = opts[j + 1].partition("=")
            envs[key] = value
    cmd = tokens[i + 1:]
    if not cmd:
        raise InvalidScript("no command after \"$IMAGE\"")
    return envs, cmd


def _arg(tok: str) -> str:
    if tok in ("$PORT", "$GPUS"):
        return f'"{tok}"'
    return shlex.quote(tok)


def generate(text: str) -> str:
    envs, cmd = extract(text)
    envs.pop("CUDA_VISIBLE_DEVICES", None)
    lines = [
        "#!/usr/bin/env bash",
        "# Generated by docker_to_direct.py: same environment and command as the docker script, without docker.",
        "set -euo pipefail",
        'PIDFILE=${PIDFILE:?set PIDFILE}; LOGFILE=${LOGFILE:?set LOGFILE}',
        'GPUS=${GPUS:-0,1,2,3}; PORT=${PORT:-8000}',
        f"command -v {shlex.quote(cmd[0])} >/dev/null || {{ echo '{cmd[0]} is not on PATH' >&2; exit 2; }}",
        'export CUDA_VISIBLE_DEVICES="$GPUS"',
    ]
    lines += [f"export {k}={shlex.quote(v)}" for k, v in envs.items()]
    lines.append("nohup " + " ".join(_arg(t) for t in cmd) + ' > "$LOGFILE" 2>&1 &')
    lines.append('echo $! > "$PIDFILE"; echo $!')
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: docker_to_direct.py <docker script>")
    sys.stdout.write(generate(open(sys.argv[1], encoding="utf-8").read()))
